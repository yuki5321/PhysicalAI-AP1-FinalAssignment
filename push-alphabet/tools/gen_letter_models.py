#!/usr/bin/env python3
"""Write Gazebo model directories for the letter blocks (Y/U/K/I ...).

Shapes, thickness, mass and friction come from pa_core/scene.yaml via
pa_core.letters.letter_sdf, so the Gazebo blocks, the 2D push model and the
real styrene-board cut-outs share one definition.

    PYTHONPATH=ros2_ws/src/pa_core python3 tools/gen_letter_models.py
    # -> ros2_ws/src/pa_description/models/letter_<X>/{model.config,model.sdf}

scene_manager spawns letters from pa_core at runtime; these model:// copies
are for manual use (Gazebo insert panel) and dataset tools.
"""

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "ros2_ws" / "src" / "pa_core"))

from pa_core.letters import letter_names, letter_sdf  # noqa: E402

DEFAULT_OUT = ROOT / "ros2_ws" / "src" / "pa_description" / "models"

CONFIG = """<?xml version="1.0"?>
<model>
  <name>{model}</name>
  <version>1.0</version>
  <sdf version="1.6">model.sdf</sdf>
  <author><name>push-alphabet</name><email>noreply@example.com</email></author>
  <description>Letter block "{letter}" (generated by tools/gen_letter_models.py from scene.yaml).</description>
</model>
"""


def write_models(out_dir: Path, letters=None) -> list:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for letter in letters or letter_names():
        model = f"letter_{letter}"
        d = out_dir / model
        d.mkdir(exist_ok=True)
        (d / "model.sdf").write_text(letter_sdf(letter, model), encoding="utf-8")
        (d / "model.config").write_text(CONFIG.format(model=model, letter=letter), encoding="utf-8")
        written.append(d)
    return written


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--letters", default=None, help='e.g. "IU" (default: all letters in scene.yaml)')
    args = ap.parse_args()
    for d in write_models(args.out, list(args.letters) if args.letters else None):
        print(d)


if __name__ == "__main__":
    main()
