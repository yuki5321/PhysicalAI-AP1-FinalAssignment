"""SDF of the point pusher (Push-T style) from scene.yaml `point_pusher`.

A vertical cylinder with no gravity, moved kinematically by
pa_gazebo point_push_executor through /set_entity_state. The model origin is
the center of the cylinder's BOTTOM face, so the model z is the gap between
the pusher and the table top.

The visual is orange with explicit ambient/diffuse/emissive (no Gazebo/*
material script, which may not resolve inside the container and then renders
white), so perception's occluder mask (saturated bright pixels) hides it.
"""

from pa_core.config import load_scene

MODEL_NAME = "point_pusher"
MASS = 0.05
COLOR = (0.95, 0.42, 0.05)      # orange, as the paddles
EMISSIVE = (0.3, 0.12, 0.0)
MU = 0.3                        # pusher <-> letter friction (as letter <-> table)


def pusher_params(scene=None) -> dict:
    scene = scene or load_scene()
    pp = scene["point_pusher"]
    return {
        "radius": float(pp["radius"]),
        "height": float(pp["height"]),
        "speed": float(pp["speed"]),
        "max_stroke": float(pp["max_stroke"]),
        "approach": float(pp["approach"]),
        "park": tuple(float(v) for v in pp["park"]),
    }


def _rgba(c) -> str:
    return f"{c[0]:.3f} {c[1]:.3f} {c[2]:.3f} 1"


def pusher_sdf(scene=None, name: str = MODEL_NAME) -> str:
    p = pusher_params(scene)
    r, h = p["radius"], p["height"]
    zc = h / 2
    ixx = MASS * (3 * r * r + h * h) / 12
    izz = MASS * r * r / 2
    geom = f"<geometry><cylinder><radius>{r:.5f}</radius><length>{h:.5f}</length></cylinder></geometry>"
    return f"""<?xml version="1.0"?>
<!-- Generated by pa_description.pusher_model from pa_core/scene.yaml (point_pusher). Do not edit.
     Kinematic point pusher, moved by pa_gazebo point_push_executor via /set_entity_state.
     Model origin = center of the cylinder's bottom face. -->
<sdf version="1.6">
  <model name="{name}">
    <link name="rod">
      <gravity>false</gravity>
      <kinematic>true</kinematic>
      <self_collide>false</self_collide>
      <inertial>
        <pose>0 0 {zc:.5f} 0 0 0</pose>
        <mass>{MASS}</mass>
        <inertia><ixx>{ixx:.4e}</ixx><iyy>{ixx:.4e}</iyy><izz>{izz:.4e}</izz><ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
      </inertial>
      <collision name="rod_collision">
        <pose>0 0 {zc:.5f} 0 0 0</pose>
        {geom}
        <surface>
          <friction><ode><mu>{MU}</mu><mu2>{MU}</mu2></ode></friction>
          <contact><ode><kp>1e5</kp><kd>10</kd><max_vel>0.1</max_vel><min_depth>0.0005</min_depth></ode></contact>
        </surface>
      </collision>
      <visual name="rod_visual">
        <pose>0 0 {zc:.5f} 0 0 0</pose>
        {geom}
        <material><ambient>{_rgba(COLOR)}</ambient><diffuse>{_rgba(COLOR)}</diffuse><specular>0.1 0.1 0.1 1</specular><emissive>{_rgba(EMISSIVE)}</emissive></material>
      </visual>
    </link>
  </model>
</sdf>
"""


def model_config(name: str = MODEL_NAME) -> str:
    return f"""<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.6">model.sdf</sdf>
  <author><name>push-alphabet</name><email>noreply@example.com</email></author>
  <description>Point pusher (Push-T style), generated by tools/gen_pusher_model.py from scene.yaml.</description>
</model>
"""
